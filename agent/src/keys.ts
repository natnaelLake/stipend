/**
 * Generate every keypair the testnet demo needs and write them to the repo-root
 * .env, which is the one place the setup script, the agent and the dashboard
 * all read from.
 *
 * Keys are generated here rather than by the NEAR CLI's keychain so that the
 * whole setup is reproducible on any machine with no OS keychain prompts —
 * which matters when a judge runs the README from a clean clone.
 */
import { KeyPair } from "near-api-js";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { randomBytes } from "node:crypto";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const envPath = resolve(repoRoot, ".env");

interface Generated {
  privateKey: string;
  publicKey: string;
}

function makeKey(): Generated {
  const kp = KeyPair.fromRandom("ed25519");
  return { privateKey: kp.toString(), publicKey: kp.getPublicKey().toString() };
}

function main(): void {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const rootArg = args.find((a) => !a.startsWith("--"));

  if (existsSync(envPath) && !force) {
    console.error(`.env already exists at ${envPath}`);
    console.error("Refusing to overwrite it — the existing keys control real testnet accounts.");
    console.error("Pass --force to regenerate (you will need to re-run the whole setup).");
    process.exit(1);
  }

  const root = rootArg ?? `warden-demo-${randomBytes(3).toString("hex")}.testnet`;
  if (!root.endsWith(".testnet")) {
    console.error(`Root account must end in .testnet, got: ${root}`);
    process.exit(1);
  }

  const owner = makeKey();
  const vault = makeKey();
  const agentFull = makeKey();
  const agentFc = makeKey();
  const merchant = makeKey();
  const attacker = makeKey();
  const stranger = makeKey();

  const lines = [
    "# Generated by: npm run gen-keys (agent/src/keys.ts)",
    "# These secret keys control testnet accounts. Never commit this file.",
    "",
    "NEAR_NETWORK=testnet",
    "",
    "# --- accounts -----------------------------------------------------------",
    `WARDEN_ROOT=${root}`,
    `OWNER_ACCOUNT_ID=${root}`,
    `VAULT_CONTRACT_ID=vault.${root}`,
    `AGENT_ACCOUNT_ID=agent1.${root}`,
    `MERCHANT_ACCOUNT_ID=merchant.${root}`,
    `ATTACKER_ACCOUNT_ID=attacker.${root}`,
    `STRANGER_ACCOUNT_ID=supplier.${root}`,
    "",
    "# --- the agent's restricted key -----------------------------------------",
    "# Added to the agent account with permission for request_payment on the",
    "# vault only. This is the single credential the agent runner is given.",
    `AGENT_FC_PRIVATE_KEY=${agentFc.privateKey}`,
    `AGENT_FC_PUBLIC_KEY=${agentFc.publicKey}`,
    "",
    "# --- full-access keys (setup and the owner demo only) -------------------",
    `OWNER_PRIVATE_KEY=${owner.privateKey}`,
    `OWNER_PUBLIC_KEY=${owner.publicKey}`,
    `VAULT_PRIVATE_KEY=${vault.privateKey}`,
    `VAULT_PUBLIC_KEY=${vault.publicKey}`,
    `AGENT_PRIVATE_KEY=${agentFull.privateKey}`,
    `AGENT_PUBLIC_KEY=${agentFull.publicKey}`,
    `MERCHANT_PRIVATE_KEY=${merchant.privateKey}`,
    `MERCHANT_PUBLIC_KEY=${merchant.publicKey}`,
    `ATTACKER_PRIVATE_KEY=${attacker.privateKey}`,
    `ATTACKER_PUBLIC_KEY=${attacker.publicKey}`,
    `STRANGER_PRIVATE_KEY=${stranger.privateKey}`,
    `STRANGER_PUBLIC_KEY=${stranger.publicKey}`,
    "",
    "# --- LLM scenarios (optional) -------------------------------------------",
    "# ANTHROPIC_API_KEY=sk-ant-...",
    "ANTHROPIC_MODEL=claude-opus-5-5",
    "",
  ];

  writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });
  console.log(`Wrote ${envPath}`);
  console.log(`Root account: ${root}`);
}

main();
